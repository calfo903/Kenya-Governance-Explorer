/** @deprecated Use countyProjects */
export const sampleProjects = countyProjects;

export function getProjectById(id: string): ProjectRecord | undefined {
  return countyProjects.find((p) => p.id === id);
}

export function getProjectsByCounty(countyCode: string): ProjectRecord[] {
  return countyProjects.filter((p) => p.countyCode === countyCode);
}

export function getAllProjects(): ProjectRecord[] {
  return countyProjects;
}

export function getStalledProjects(): ProjectRecord[] {
  return countyProjects.filter((p) => p.status === 'stalled' || p.status === 'suspended');
}

export function getProjectsByCategory(category: string): ProjectRecord[] {
  return countyProjects.filter((p) => p.category.toLowerCase().includes(category.toLowerCase()));
}
