export function getMemberById(id: string): MzalendoMember | undefined {
  return mzalendoMembers.find(m => m.id === id);
}

export function getMembersByCounty(county: string): MzalendoMember[] {
  return mzalendoMembers.filter(m => m.county === county);
}

export function getAllMembers(): MzalendoMember[] {
  return mzalendoMembers;
}

export function getMembersByGender(gender: 'male' | 'female'): MzalendoMember[] {
  return mzalendoMembers.filter(m => m.gender === gender);
}
